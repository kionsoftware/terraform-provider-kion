package kalign

import (
	"fmt"
	"io"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// Baseline maps a Finding key to the reason it is accepted.
type Baseline map[string]string

// LoadBaseline reads a baseline file. A missing file is an error: an absent
// baseline must not read as "nothing is accepted" and pass on nothing.
func LoadBaseline(path string) (Baseline, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	b := Baseline{}
	if err := yaml.Unmarshal(raw, &b); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	return b, nil
}

// CompareBaseline returns the findings the baseline does not record and the
// baseline keys that no longer occur, both sorted.
func CompareBaseline(findings []Finding, b Baseline) (unexpected []Finding, stale []string) {
	seen := make(map[string]bool, len(findings))
	for _, f := range findings {
		seen[f.Key()] = true
		if _, ok := b[f.Key()]; !ok {
			unexpected = append(unexpected, f)
		}
	}
	for k := range b {
		if !seen[k] {
			stale = append(stale, k)
		}
	}
	sort.Slice(unexpected, func(i, j int) bool { return unexpected[i].Key() < unexpected[j].Key() })
	sort.Strings(stale)
	return unexpected, stale
}

// ReportRatchet writes the ratchet verdict to w and reports whether it passes:
// no finding outside the baseline, no stale entry, and a triaged (non-TODO)
// reason on every entry.
func ReportRatchet(w io.Writer, findings []Finding, b Baseline, path string) bool {
	ew := &errWriter{w: w}
	unexpected, stale := CompareBaseline(findings, b)
	var unexplained []string
	for k, reason := range b {
		if r := strings.TrimSpace(reason); r == "" || strings.HasPrefix(r, "TODO") {
			unexplained = append(unexplained, k)
		}
	}
	sort.Strings(unexplained)

	for _, f := range unexpected {
		ew.Fprintf("NEW    %s (not in %s): fix it, or record why it is accepted\n", f.Key(), path)
	}
	for _, k := range stale {
		ew.Fprintf("STALE  %s (in %s, no longer found): drop the entry\n", k, path)
	}
	for _, k := range unexplained {
		ew.Fprintf("REASON %s (in %s) has no reason (TODO or empty)\n", k, path)
	}
	ok := len(unexpected)+len(stale)+len(unexplained) == 0
	if ok {
		ew.Fprintf("align-check: %d finding(s), all recorded in %s\n", len(findings), path)
	} else {
		ew.Fprintf("align-check FAILED against %s; rewrite with: kalign check -update\n", path)
	}
	return ok
}

// WriteBaseline rewrites path from findings, carrying existing reasons forward;
// a finding without one arrives as TODO.
func WriteBaseline(path string, findings []Finding, prev Baseline) error {
	var b strings.Builder
	b.WriteString(baselineHeader)
	sorted := append([]Finding(nil), findings...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Key() < sorted[j].Key() })
	for _, f := range sorted {
		reason := prev[f.Key()]
		if strings.TrimSpace(reason) == "" {
			reason = "TODO: untriaged"
		}
		fmt.Fprintf(&b, "%s: %q\n", f.Key(), reason)
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

const baselineHeader = `# align-check (kalign check) findings that are known and accepted.
#
# Generated by: make align-baseline   (kalign check -update)
# Guarded by:   make align-check      (in make ci and the align-check CI job)
#
# Each key is <service>.<attribute>:<kind>. kind "type" means the schema and
# the SDK field it aligned to disagree on primitive type; "flex" means the
# flatten converter kalign derives for that SDK type does not exist.
#
# kalign compares one schema model to one SDK struct, so an attribute bound
# through a mechanism it cannot see still reports. Each reason names that
# mechanism. A new finding fails the check, and so does an entry that no
# longer occurs. Reasons are preserved across -update; new entries arrive as
# TODO and must be triaged before merging.

`
