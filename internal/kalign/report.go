package kalign

import (
	"fmt"
	"io"
)

// errWriter wraps an io.Writer and remembers the first write error, so the
// report builders can emit many lines and the caller checks the error once at
// the end instead of after every Fprintf (the classic Effective Go pattern).
type errWriter struct {
	w   io.Writer
	err error
}

// Fprintf writes a formatted line, becoming a no-op once a prior write failed.
func (ew *errWriter) Fprintf(format string, a ...any) {
	if ew.err != nil {
		return
	}
	_, ew.err = fmt.Fprintf(ew.w, format, a...)
}

// Fprintln writes a line, becoming a no-op once a prior write failed.
func (ew *errWriter) Fprintln(a ...any) {
	if ew.err != nil {
		return
	}
	_, ew.err = fmt.Fprintln(ew.w, a...)
}

// checkOne writes a human-readable drift report for one resolved model to w and
// returns the number of ACTIONABLE findings (0 means nothing to fix). DRIFT
// lines are still printed, but are advisory; see Resolved.Actionable.
func checkOne(w *errWriter, r Resolved) int {
	w.Fprintf("\n=== %s (%s) ===\n", r.Model.Service, r.Model.Name)
	if r.SDKType == "" {
		w.Fprintln("  ! no SDK type overlaps this model's tfsdk fields")
		return r.Actionable()
	}
	conf := ""
	if r.LowConfidence {
		conf = "  [LOW CONFIDENCE: verify the type]"
	}
	w.Fprintf("  SDK type: generated.%s (overlap %d/%d)%s\n", r.SDKType, r.Overlap, len(r.Model.Fields), conf)
	for _, p := range r.Pairs {
		mark := "ok   "
		switch {
		case p.Nested:
			mark = "nest "
		case !p.HaveFlex:
			mark = "FLEX "
		}
		w.Fprintf("    %s %s -> %s\n", mark, p.Model.TFSDK, p.SDK.GoType)
	}
	for _, miss := range r.MissingInSDK {
		// Advisory: printed for a human reading the report, not counted. See
		// Resolved.Actionable for why.
		w.Fprintf("    DRIFT no SDK field for schema attribute %q (advisory)\n", miss)
	}
	for _, tm := range r.TypeMismatch {
		w.Fprintf("    TYPE  %s\n", tm)
	}
	for _, mf := range r.MissingFlex {
		w.Fprintf("    FLEX  missing converter %s\n", mf)
	}
	return r.Actionable()
}

// genOne writes the flatten (SDK -> Framework) converter for one resolved model
// to w. It returns the count of fields it could not emit (nested attrs + missing
// flex converters), which are written as TODO comments instead of code.
func genOne(w *errWriter, r Resolved) int {
	if r.SDKType == "" || r.LowConfidence {
		w.Fprintf("// %s: skipped (no confident SDK type match)\n\n", r.Model.Service)
		return len(r.NestedAttrs) + len(r.MissingFlex)
	}
	recv := goExported(r.Model.Service)
	w.Fprintf("// flatten%s copies a generated.%s into a %s.\n", recv, r.SDKType, r.Model.Name)
	w.Fprintf("// Code generated by kalign; DO NOT EDIT.\n")
	w.Fprintf("func flatten%s(in *generated.%s, m *%s) {\n", recv, r.SDKType, r.Model.Name)
	todos := 0
	for _, p := range r.Pairs {
		switch {
		case p.Nested:
			todos++
			w.Fprintf("\t// TODO(nested): m.%s = ... (SDK %s): nested object, needs a nested converter\n", p.Model.GoName, p.SDK.GoType)
		case !p.HaveFlex:
			todos++
			w.Fprintf("\t// TODO(flex): m.%s = flex.%s(in.%s): converter does not exist yet\n", p.Model.GoName, p.FlexFn, p.SDK.GoName)
		default:
			w.Fprintf("\tm.%s = flex.%s(in.%s)\n", p.Model.GoName, p.FlexFn, p.SDK.GoName)
		}
	}
	w.Fprintf("}\n\n")
	return todos
}
