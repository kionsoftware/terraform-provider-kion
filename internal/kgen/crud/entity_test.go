func TestIDParamName_types(t *testing.T) {
	n, ty, err := idParamName(&Struct{Name: "P", Fields: []Field{{GoName: "ID", Type: "uint64"}}})
	if err != nil || n != "ID" || ty != "uint64" {
		t.Fatalf("uint64: got %q,%q,%v", n, ty, err)
	}
	n, ty, err = idParamName(&Struct{Name: "P", Fields: []Field{{GoName: "ID", Type: "int64"}}})
	if err != nil || n != "ID" || ty != "int64" {
		t.Fatalf("int64: got %q,%q,%v", n, ty, err)
	}
	n, ty, err = idParamName(&Struct{Name: "P", Fields: []Field{{GoName: "ID", Type: "string"}}})
	if err != nil || n != "ID" || ty != "string" {
		t.Fatalf("string: got %q,%q,%v", n, ty, err)
	}
	if _, _, err := idParamName(&Struct{Name: "P", Fields: []Field{{GoName: "Name", Type: "string"}}}); err == nil {
		t.Fatal("want error for a required string param not named like an id")
	}
	if _, _, err := idParamName(&Struct{Name: "P", Fields: []Field{{GoName: "ID", Type: "bool"}}}); err == nil {
		t.Fatal("want error for a non-int, non-string id param")
	}
}

func TestRenderEntity_label(t *testing.T) {
	got, err := renderEntity(labelResourceModel(t))
	if err != nil {
		t.Fatalf("renderEntity: %v", err)
	}

	// Semantic fidelity: it must parse as Go and call the same SDK ops / map
	// the same fields as the golden hand-written label.go.
	if _, err := parser.ParseFile(token.NewFileSet(), "label.go", got, parser.ParseComments); err != nil {
		t.Fatalf("generated label.go does not parse: %v\n%s", err, got)
	}

	wants := []string{
		"// Code generated by kgen crud. DO NOT EDIT.",
		"package label",
		"func (r *labelResource) Create(",
		"func (r *labelResource) Read(",
		"func (r *labelResource) Update(",
		"func (r *labelResource) Delete(",
		"func (r *labelResource) ImportState(",
		"conn.PostLabel(ctx, input)",
		"errs.CreatedID(out)",
		"generated.GetLabelParams{ID: id}",
		"generated.GetLabelParams{ID: idInt}",
		"conn.PatchLabel(ctx, input, generated.PatchLabelParams{ID: idInt})",
		"conn.DeleteLabel(ctx, generated.DeleteLabelParams{ID: idInt})",
		"errs.IsNotFound(out)",
		"resp.State.RemoveResource(ctx)",
		"flex.StringValueFromFramework(plan.Key)",
		"flex.OptStringFromFramework(plan.Key)",
		"func flattenLabel(",
		"strconv.FormatUint(v.Data.Value.ID.Value, 10)",
		"flex.StringToFramework(v.Data.Value.Key)",
	}
	for _, w := range wants {
		if !bytes.Contains(got, []byte(w)) {
			t.Errorf("generated label.go missing %q", w)
		}
	}
}

// An attribute the update body cannot carry but a dedicated move endpoint can
// is moved before the PATCH: over raw HTTP for a private route, or through the
// account move, which answers with the account's new id.
func TestRenderEntity_moves(t *testing.T) {
	rm := labelResourceModel(t)
	rm.Moves = []moveBind{
		{ModelGo: "Color", TF: "color", RawPost: "/v2/label/{id}/move"},
		{ModelGo: "Key", TF: "key", AccountMove: true},
	}
	got, err := renderEntity(rm)
	if err != nil {
		t.Fatalf("renderEntity: %v", err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "label.go", got, parser.ParseComments); err != nil {
		t.Fatalf("does not parse: %v\n%s", err, got)
	}
	for _, w := range []string{
		"req.State.Get(ctx, &state)",
		"!plan.Color.Equal(state.Color)",
		`r.Meta().RawPost(ctx, strings.Replace("/v2/label/{id}/move", "{id}", strconv.FormatInt(idInt, 10), 1), moveBody)`,
		"json.Marshal(plan.Color.ValueInt64())",
		"accounthelper.MoveAccountBetweenProjects(ctx, conn, idInt, uint64(plan.Key.ValueInt64()), \"preserve\", 0)",
		"idInt = moved.NewID",
		// A completed move is recorded at once, so a later failure in Update
		// cannot leave state pointing at the old parent or the old account id.
		`resp.State.SetAttribute(ctx, path.Root("color"), plan.Color)`,
		`resp.State.SetAttribute(ctx, path.Root("key"), plan.Key)`,
		`resp.State.SetAttribute(ctx, path.Root("id"), plan.Id)`,
		`"terraform-provider-kion/internal/service/accounthelper"`,
	} {
		if !bytes.Contains(got, []byte(w)) {
			t.Errorf("missing %q\n%s", w, got)
		}
	}
	plain, err := renderEntity(labelResourceModel(t))
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Contains(plain, []byte("accounthelper")) {
		t.Error("accounthelper imported without a move")
	}
}

