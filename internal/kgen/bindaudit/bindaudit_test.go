// BaselinePath records the settable attributes the provider does not send
// today, each with a reason. It is a ratchet, not an allowlist: the point is
// that adding to it is a deliberate, reviewed act.
const BaselinePath = "codegen/unbound_attributes.yaml"

var update = flag.Bool("update", false, "rewrite "+BaselinePath+" from the current tree")

// TestNoDroppedRequestAttributes fails when a resource accepts an attribute its
// Create or Update never reads -- input the provider takes and discards --
// unless the baseline already records it.
//
// It fails in both directions on purpose. A NEW dropped attribute is the bug
// this exists to catch (#61, #64). A baseline entry that no longer reproduces
// means someone bound the attribute and left a stale excuse behind, and stale
// excuses are how a ratchet quietly turns back into an allowlist.
func TestNoDroppedRequestAttributes(t *testing.T) {
	t.Parallel()
	root := projectRoot(t)

	findings, err := bindaudit.Run(root)
	require.NoError(t, err)

	baseline := loadBaseline(t, filepath.Join(root, BaselinePath))

	if *update {
		writeBaseline(t, filepath.Join(root, BaselinePath), findings, baseline)
		t.Logf("wrote %s (%d findings)", BaselinePath, len(findings))
		return
	}

	current := map[string]bindaudit.Finding{}
	for _, f := range findings {
		current[f.Key()] = f
	}

	var added []string
	for _, f := range findings {
		if _, ok := baseline[f.Key()]; !ok {
			added = append(added, fmt.Sprintf("  %s (%s builds %s)", f.Key(), f.Op, f.Body))
		}
	}
	var stale []string
	for key := range baseline {
		if _, ok := current[key]; !ok {
			stale = append(stale, "  "+key)
		}
	}
	sort.Strings(added)
	sort.Strings(stale)

	assert.Empty(t, added, "these attributes are settable in the schema but never read by the "+
		"operation named -- the provider accepts the value and discards it.\n"+
		strings.Join(added, "\n")+
		"\n\nBind them, or record why not:  go test ./internal/kgen/bindaudit/ -update")

	assert.Empty(t, stale, BaselinePath+" lists attributes that are now bound; drop these entries:\n"+
		strings.Join(stale, "\n")+
		"\n\nOr regenerate:  go test ./internal/kgen/bindaudit/ -update")
}

// TestIssueRegressionsStayFixed pins the two attributes whose loss motivated
// this audit. They must never reappear in the baseline: a regression here is
// not a categorization question, it is the bug coming back.
func TestIssueRegressionsStayFixed(t *testing.T) {
	t.Parallel()
	root := projectRoot(t)

	findings, err := bindaudit.Run(root)
	require.NoError(t, err)

	dropped := map[string]bool{}
	for _, f := range findings {
		dropped[f.Key()] = true
	}

	for _, key := range []string{
		// #61: one polymorphic SDK field, three typed schema attributes.
		"custom_variable.default_value_string:create",
		"custom_variable.default_value_list:create",
		"custom_variable.default_value_map:create",
		"custom_variable.default_value_string:update",
		"custom_variable.default_value_list:update",
		"custom_variable.default_value_map:update",
		// #64: the update body was `{}`.
		"permission_scheme.name:update",
		"permission_scheme.type:update",
		"permission_scheme.roles:update",
	} {
		assert.False(t, dropped[key], "%s is dropped again -- see GitHub #61 / #64", key)
	}
}

func loadBaseline(t *testing.T, path string) map[string]string {
	t.Helper()
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return map[string]string{}
	}
	require.NoError(t, err)
	out := map[string]string{}
	require.NoError(t, yaml.Unmarshal(raw, &out))
	return out
}

// writeBaseline rewrites the file, carrying existing reasons forward so
// regenerating never silently discards someone's categorization.
func writeBaseline(t *testing.T, path string, findings []bindaudit.Finding, prev map[string]string) {
	t.Helper()

	var b strings.Builder
	b.WriteString("# Settable attributes the provider accepts and never sends.\n")
	b.WriteString("#\n")
	b.WriteString("# Generated by: go test ./internal/kgen/bindaudit/ -update\n")
	b.WriteString("# Guarded by:   TestNoDroppedRequestAttributes\n")
	b.WriteString("#\n")
	b.WriteString("# Each key is <package>.<attribute>:<op>. Its presence means the operation\n")
	b.WriteString("# builds its request without reading that attribute, so configuring it has\n")
	b.WriteString("# no effect. Most entries are a request body with no field for the\n")
	b.WriteString("# attribute; the reason names the body so a reviewer can check.\n")
	b.WriteString("#\n")
	b.WriteString("# This is a ratchet over pre-existing debt, NOT a statement that any entry\n")
	b.WriteString("# is acceptable. An entry marked TODO has not been triaged. Fixing one means\n")
	b.WriteString("# either binding the attribute or, where the API genuinely cannot change it\n")
	b.WriteString("# in place, marking it RequiresReplace -- which removes it from the update\n")
	b.WriteString("# side of this audit for the right reason.\n")
	b.WriteString("#\n")
	b.WriteString("# Reasons are preserved across regeneration; new entries arrive as TODO.\n\n")

	for _, f := range findings {
		reason, ok := prev[f.Key()]
		if !ok || strings.TrimSpace(reason) == "" {
			reason = defaultReason(f)
		}
		fmt.Fprintf(&b, "%s: %q\n", f.Key(), reason)
	}

	require.NoError(t, os.WriteFile(path, []byte(b.String()), 0o644))
}

// defaultReason states the fact the audit established, and nothing more: a new
// entry is untriaged until a human says otherwise.
func defaultReason(f bindaudit.Finding) string {
	if f.Body == "" {
		return "TODO: untriaged -- " + f.Op + " never reads this attribute"
	}
	return "TODO: untriaged -- " + f.Op + " builds " + f.Body + " without it"
}

// projectRoot walks up until it finds go.mod.
func projectRoot(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	require.NoError(t, err)
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		require.NotEqual(t, parent, dir, "go.mod not found above the test's working directory")
		dir = parent
	}
}
