package migrate

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"testing"
)

var updateRemoved = flag.Bool("update", false, "rewrite removed.go from the schema snapshots")

// removed.go is derived from the snapshots, which kmigrate does not ship. It
// must name every attribute an old resource has and the new one lacks, or a
// reference to it passes kmigrate and fails `terraform plan`.
func TestRemovedAttrsAreCurrent(t *testing.T) {
	oldS, err := LoadSchema(oldSnap)
	if err != nil {
		t.Fatal(err)
	}
	newS, err := LoadSchema(newSnap)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]string{}
	for rtype, o := range oldS {
		n, ok := newS[rtype]
		if !ok {
			continue
		}
		for a := range o.Attrs {
			if _, kept := n.Attrs[a]; !kept {
				want[rtype] = append(want[rtype], a)
			}
		}
		sort.Strings(want[rtype])
	}

	src := renderRemoved(t, want)
	if *updateRemoved {
		if err := os.WriteFile("removed.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("removed.go")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(src) {
		t.Fatal("removed.go is stale against codegen/schema_snapshots; regenerate:  go test ./internal/kgen/migrate/ -run TestRemovedAttrsAreCurrent -update")
	}
}

func renderRemoved(t *testing.T, m map[string][]string) []byte {
	t.Helper()
	var b strings.Builder
	b.WriteString("// Code generated by: go test ./internal/kgen/migrate/ -run TestRemovedAttrsAreCurrent -update. DO NOT EDIT.\n\n")
	b.WriteString("package migrate\n\n")
	b.WriteString("// RemovedAttrs lists, per resource type, every attribute and block the old\n")
	b.WriteString("// schema had that the new one does not, settable or computed. kmigrate reports\n")
	b.WriteString("// a reference to one, since the reference fails `terraform plan`.\n")
	b.WriteString("var RemovedAttrs = map[string][]string{\n")
	for _, rtype := range sortedKeys(m) {
		fmt.Fprintf(&b, "\t%q: {", rtype)
		for i, a := range m[rtype] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", a)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		t.Fatal(err)
	}
	return src
}
