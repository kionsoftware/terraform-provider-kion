package migrate

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"testing"
)

var updateRemoved = flag.Bool("update", false, "rewrite removed.go from the schema snapshots")

// removed.go is derived from the snapshots, which kmigrate does not ship. It
// must name every attribute an old resource has and the new one lacks, or a
// reference to it passes kmigrate and fails `terraform plan`.
func TestRemovedAttrsAreCurrent(t *testing.T) {
	oldS, err := LoadSchema(oldSnap)
	if err != nil {
		t.Fatal(err)
	}
	newS, err := LoadSchema(newSnap)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]string{}
	for rtype, o := range oldS {
		n, ok := newS[rtype]
		if !ok {
			continue
		}
		for a := range o.Attrs {
			if _, kept := n.Attrs[a]; !kept {
				want[rtype] = append(want[rtype], a)
			}
		}
		sort.Strings(want[rtype])
	}

	wantDS := removedDataSourceAttrs(t)

	src := renderRemoved(t, want, wantDS)
	if *updateRemoved {
		if err := os.WriteFile("removed.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("removed.go")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(src) {
		t.Fatal("removed.go is stale against codegen/schema_snapshots; regenerate:  go test ./internal/kgen/migrate/ -run TestRemovedAttrsAreCurrent -update")
	}
}

// removedDataSourceAttrs is the data-source half: LoadSchema reads resources
// only, and a reference needs no more than the top-level attribute names.
func removedDataSourceAttrs(t *testing.T) map[string][]string {
	t.Helper()
	names := func(path string) map[string]map[string]bool {
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		var doc struct {
			ProviderSchemas map[string]struct {
				DataSourceSchemas map[string]struct {
					Block struct {
						Attributes map[string]json.RawMessage `json:"attributes"`
						BlockTypes map[string]json.RawMessage `json:"block_types"`
					} `json:"block"`
				} `json:"data_source_schemas"`
			} `json:"provider_schemas"`
		}
		if err := json.Unmarshal(raw, &doc); err != nil {
			t.Fatalf("parse %s: %v", path, err)
		}
		out := map[string]map[string]bool{}
		for _, ps := range doc.ProviderSchemas {
			for dtype, ds := range ps.DataSourceSchemas {
				out[dtype] = map[string]bool{}
				for a := range ds.Block.Attributes {
					out[dtype][a] = true
				}
				for a := range ds.Block.BlockTypes {
					out[dtype][a] = true
				}
			}
		}
		return out
	}
	oldDS, newDS := names(oldSnap), names(newSnap)
	m := map[string][]string{}
	for dtype, attrs := range oldDS {
		kept, ok := newDS[dtype]
		if !ok {
			continue
		}
		for a := range attrs {
			if !kept[a] {
				m[dtype] = append(m[dtype], a)
			}
		}
		sort.Strings(m[dtype])
	}
	return m
}

func renderRemoved(t *testing.T, res, ds map[string][]string) []byte {
	t.Helper()
	var b strings.Builder
	b.WriteString("// Code generated by: go test ./internal/kgen/migrate/ -run TestRemovedAttrsAreCurrent -update. DO NOT EDIT.\n\n")
	b.WriteString("package migrate\n\n")
	writeMap := func(name, doc string, m map[string][]string) {
		b.WriteString(doc)
		fmt.Fprintf(&b, "var %s = map[string][]string{\n", name)
		for _, typ := range sortedKeys(m) {
			fmt.Fprintf(&b, "\t%q: {", typ)
			for i, a := range m[typ] {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", a)
			}
			b.WriteString("},\n")
		}
		b.WriteString("}\n")
	}
	writeMap("RemovedAttrs", "// RemovedAttrs lists, per resource type, every attribute and block the old\n"+
		"// schema had that the new one does not, settable or computed. kmigrate reports\n"+
		"// a reference to one, since the reference fails `terraform plan`.\n", res)
	b.WriteString("\n")
	writeMap("RemovedDataSourceAttrs", "// RemovedDataSourceAttrs is RemovedAttrs for data sources, top-level only.\n", ds)
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		t.Fatal(err)
	}
	return src
}
